# Atividade 1: saudação e operações matemáticas simples

# Variável com o nome do personagem
nome = "Harry Potter"
# Cria uma mensagem personalizada usando f-string
mensagem = f"Olá, {nome}!"
print(mensagem)

print("Vamos fazer algumas contas:")

# A multiplicação tem prioridade antes da soma
conta = 2 + 3 * 4
# Soma simples para comparar o resultado
soma = 10 + 5

# Exibe os resultados das operações
print(f"2 + 3 * 4 = {conta}")
print(f"10 + 5 = {soma}")

print("Fim da sessão!")